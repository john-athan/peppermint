// peppermint's build: tools/build-app.ts does the shared work (oss-kit's bun-app template); this file is what is peppermint's own.
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { buildApp } from "./tools/build-app";
import { mark, leafSvg, iconSvg } from "./shared/logo.mjs";

const root = import.meta.dir;
writeFileSync(join(root, "client/lib/marks.gen.ts"), `// generated by build.ts from shared/logo.mjs\nexport const MARK = ${JSON.stringify(mark())};\n`);

// the natural voice's worker: its name carries a hash of its content, so no cache anywhere hands out an older one
const workerSrc = readFileSync(join(root, "client/voice-worker.js"), "utf8");
const workerPath = `/assets/voice-worker-${Bun.hash(workerSrc).toString(36)}.js`;
const SHORTCUT_ICON = [{ src: "/icon-192.png", sizes: "192x192" }];

await buildApp({
  root,
  prepare({ out }) {
    writeFileSync(join(out, workerPath.slice(1)), workerSrc);
    return { __VOICE_WORKER__: JSON.stringify(workerPath) };
  },
  // the shimmer's leaf comes from the mark itself: app.css says PM_LEAF where the data URI goes
  css: () => readFileSync(join(root, "client/app.css"), "utf8").replaceAll("PM_LEAF", `url("data:image/svg+xml,${encodeURIComponent(leafSvg())}")`),
  icon: iconSvg(),
  precache: [workerPath],
  compress: /./,
  manifest: icons => ({
    name: "peppermint", short_name: "peppermint", start_url: "/", display: "standalone", background_color: "#e8f7ec", theme_color: "#e8f7ec",
    id: "/", scope: "/", lang: "en", description: "Everything you follow, distilled to your taste.", categories: ["news", "productivity"],
    display_override: ["standalone", "minimal-ui"],
    // links and photos from the system share sheet: the service worker reads the post (photos go to the capture sheet, a link to the agent)
    share_target: { action: "/share", method: "POST", enctype: "multipart/form-data", params: { title: "title", text: "text", url: "url", files: [{ name: "photo", accept: ["image/*", ".jpg", ".jpeg", ".png", ".heic"] }] } },
    icons,
    shortcuts: [
      { name: "Today", url: "/", icons: SHORTCUT_ICON },
      { name: "Reading list", url: "/list", icons: SHORTCUT_ICON },
      { name: "Listen", url: "/listen", icons: SHORTCUT_ICON },
    ],
  }),
  // the vendored kokoro bundle is served only to signed-in devices (/voice/), so it is not in the manifest's list
  after({ out }) { writeFileSync(join(out, "kokoro.web.js"), readFileSync(join(root, "vendor/kokoro.web.js"))); },
});
